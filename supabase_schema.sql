-- Dream Diary: run this entire file in Supabase SQL Editor.
-- User accounts are managed by Supabase Auth (auth.users). Never create a password table.

create table if not exists public.dreams (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  content text not null,
  emotion text not null,
  tags text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.sleep_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sleep_time text not null,
  wake_time text not null,
  duration_minutes integer not null check (duration_minutes >= 0),
  quality integer not null check (quality between 1 and 10),
  note text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists dreams_user_created_idx on public.dreams(user_id, created_at desc);
create index if not exists sleep_records_user_created_idx on public.sleep_records(user_id, created_at desc);

alter table public.dreams enable row level security;
alter table public.sleep_records enable row level security;

drop policy if exists "Users can view their own dreams" on public.dreams;
create policy "Users can view their own dreams" on public.dreams
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own dreams" on public.dreams;
create policy "Users can insert their own dreams" on public.dreams
  for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own dreams" on public.dreams;
create policy "Users can update their own dreams" on public.dreams
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own dreams" on public.dreams;
create policy "Users can delete their own dreams" on public.dreams
  for delete to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Users can view their own sleep records" on public.sleep_records;
create policy "Users can view their own sleep records" on public.sleep_records
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own sleep records" on public.sleep_records;
create policy "Users can insert their own sleep records" on public.sleep_records
  for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own sleep records" on public.sleep_records;
create policy "Users can update their own sleep records" on public.sleep_records
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own sleep records" on public.sleep_records;
create policy "Users can delete their own sleep records" on public.sleep_records
  for delete to authenticated using ((select auth.uid()) = user_id);

-- Allow signed-in clients to access the tables; RLS still restricts each row to its owner.
grant select, insert, update, delete on public.dreams to authenticated;
grant select, insert, update, delete on public.sleep_records to authenticated;
grant usage, select on all sequences in schema public to authenticated;
